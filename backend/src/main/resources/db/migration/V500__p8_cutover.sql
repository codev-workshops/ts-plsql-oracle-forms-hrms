-- P8 parity + cutover (range V500-V599). Appended; never edits V1..V400.

-- PKG-L05 / DEF-03: year-end carryover and carryover expiry become idempotent runs, like
-- leave_accrual_runs (V10). A CARRYOVER run is keyed by the first day of the new year, an EXPIRY run by
-- its as-of date; re-running either returns the existing run and changes nothing.
CREATE TABLE hrms.leave_carryover_runs (
    run_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    run_type             VARCHAR(20)     NOT NULL,
    run_key              DATE            NOT NULL,
    from_year            INTEGER,
    balances_processed   INTEGER         NOT NULL,
    total_days           NUMERIC(9,2)    NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_leave_carryover_runs PRIMARY KEY (run_id),
    CONSTRAINT uk_carryover_run UNIQUE (run_type, run_key),
    CONSTRAINT chk_carryover_run_type CHECK (run_type IN ('CARRYOVER', 'EXPIRY')),
    CONSTRAINT chk_carryover_run_year CHECK (run_type <> 'CARRYOVER'
        OR (from_year IS NOT NULL AND run_key = make_date(from_year + 1, 1, 1)))
);

COMMENT ON TABLE hrms.leave_carryover_runs IS 'One row per carryover (per year) or expiry (per as-of date) run (P8, PKG-L05, DEF-03)';

CREATE TABLE hrms.leave_carryover_log (
    log_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    run_id               BIGINT          NOT NULL,
    emp_id               BIGINT          NOT NULL,
    leave_type_id        BIGINT          NOT NULL,
    calendar_year        INTEGER         NOT NULL,
    days                 NUMERIC(6,2)    NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_leave_carryover_log PRIMARY KEY (log_id),
    CONSTRAINT fk_lcl_run FOREIGN KEY (run_id) REFERENCES hrms.leave_carryover_runs (run_id),
    CONSTRAINT fk_lcl_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT fk_lcl_type FOREIGN KEY (leave_type_id) REFERENCES hrms.leave_types (leave_type_id),
    CONSTRAINT uk_lcl_run_emp_type UNIQUE (run_id, emp_id, leave_type_id)
);

CREATE INDEX ix_lcl_emp ON hrms.leave_carryover_log (emp_id);
CREATE INDEX ix_lcl_type ON hrms.leave_carryover_log (leave_type_id);
CREATE INDEX ix_lb_carryover_expiry ON hrms.leave_balances (carryover_expiry_dt) WHERE carryover_from_prev > 0;

-- OQ-15 (production half): migrated employees get an unusable password and a one-time reset link.
ALTER TABLE hrms.user_credentials
    ADD COLUMN reset_required BOOLEAN DEFAULT false NOT NULL;

COMMENT ON COLUMN hrms.user_credentials.reset_required IS 'true while the hash is an unusable placeholder; cleared by a password reset (OQ-15)';

CREATE TABLE hrms.password_reset_tokens (
    token_id             BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    token_hash           VARCHAR(64)     NOT NULL,
    expires_at           TIMESTAMPTZ     NOT NULL,
    used_at              TIMESTAMPTZ,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_password_reset_tokens PRIMARY KEY (token_id),
    CONSTRAINT uk_password_reset_token UNIQUE (token_hash),
    CONSTRAINT fk_prt_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id)
);

COMMENT ON TABLE hrms.password_reset_tokens IS 'One-time password reset tokens (OQ-15); only the SHA-256 hex is stored. used_at is set on use or when a newer token supersedes it';

CREATE INDEX ix_prt_emp ON hrms.password_reset_tokens (emp_id) WHERE used_at IS NULL;

