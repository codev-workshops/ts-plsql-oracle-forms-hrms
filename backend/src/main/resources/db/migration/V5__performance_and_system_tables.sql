-- REVIEW_CYCLES (SEQ_REVIEW_CYCLE START WITH 1)
CREATE TABLE hrms.review_cycles (
    cycle_id             BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    cycle_name           VARCHAR(100)    NOT NULL,
    cycle_year           INTEGER         NOT NULL,
    start_date           DATE            NOT NULL,
    end_date             DATE            NOT NULL,
    self_review_due      DATE,
    manager_review_due   DATE,
    calibration_due      DATE,
    status               VARCHAR(20)     DEFAULT 'DRAFT',
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_review_cycles PRIMARY KEY (cycle_id),
    CONSTRAINT chk_cycle_status CHECK (status IN ('DRAFT', 'OPEN', 'IN_PROGRESS', 'CALIBRATION', 'CLOSED'))
);

-- PERFORMANCE_REVIEWS (SEQ_PERF_REVIEW START WITH 1)
CREATE TABLE hrms.performance_reviews (
    review_id            BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    cycle_id             BIGINT          NOT NULL,
    emp_id               BIGINT          NOT NULL,
    reviewer_emp_id      BIGINT          NOT NULL,
    review_type          VARCHAR(20)     DEFAULT 'ANNUAL',
    status               VARCHAR(20)     DEFAULT 'NOT_STARTED',
    overall_rating       NUMERIC(2,1),
    rating_label         VARCHAR(50),
    self_assessment      TEXT,
    manager_assessment   TEXT,
    strengths            TEXT,
    areas_for_improvement TEXT,
    development_plan     TEXT,
    employee_comments    TEXT,
    employee_ack_date    TIMESTAMPTZ,
    calibrated_rating    NUMERIC(2,1),
    calibration_notes    VARCHAR(4000),
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_performance_reviews PRIMARY KEY (review_id),
    CONSTRAINT fk_pr_cycle FOREIGN KEY (cycle_id) REFERENCES hrms.review_cycles (cycle_id),
    CONSTRAINT fk_pr_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT fk_pr_reviewer FOREIGN KEY (reviewer_emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT chk_review_status CHECK (status IN ('NOT_STARTED', 'SELF_REVIEW', 'MANAGER_REVIEW', 'MEETING_SCHEDULED', 'COMPLETED', 'ACKNOWLEDGED')),
    CONSTRAINT chk_rating_range CHECK (overall_rating BETWEEN 1.0 AND 5.0)
);

-- PERFORMANCE_GOALS (SEQ_PERF_GOAL START WITH 1)
CREATE TABLE hrms.performance_goals (
    goal_id              BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    review_id            BIGINT          NOT NULL,
    emp_id               BIGINT          NOT NULL,
    goal_title           VARCHAR(200)    NOT NULL,
    goal_description     TEXT,
    goal_category        VARCHAR(30),
    weight_pct           NUMERIC(5,2)    DEFAULT 0,
    target_date          DATE,
    status               VARCHAR(20)     DEFAULT 'NOT_STARTED',
    progress_pct         NUMERIC(5,2)    DEFAULT 0,
    self_rating          NUMERIC(2,1),
    manager_rating       NUMERIC(2,1),
    comments             TEXT,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_perf_goals PRIMARY KEY (goal_id),
    CONSTRAINT fk_pg_review FOREIGN KEY (review_id) REFERENCES hrms.performance_reviews (review_id),
    CONSTRAINT fk_pg_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT chk_goal_status CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED', 'DEFERRED', 'CANCELLED')),
    CONSTRAINT chk_goal_category CHECK (goal_category IN ('BUSINESS', 'DEVELOPMENT', 'LEADERSHIP', 'INNOVATION', 'COMPLIANCE'))
);

-- AUDIT_LOG (SEQ_AUDIT START WITH 1 CACHE 100)
-- D-08: JSONB payloads; STATUS_CHANGE added (DEF-15); action_type widened from 10 to 20
-- because 'STATUS_CHANGE' is 13 characters.
CREATE TABLE hrms.audit_log (
    audit_id             BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1 CACHE 100) NOT NULL,
    table_name           VARCHAR(60)     NOT NULL,
    record_id            BIGINT          NOT NULL,
    action_type          VARCHAR(20)     NOT NULL,
    old_values           JSONB,
    new_values           JSONB,
    changed_by           VARCHAR(100)    NOT NULL,
    changed_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ip_address           VARCHAR(50),
    session_id           VARCHAR(100),
    CONSTRAINT pk_audit_log PRIMARY KEY (audit_id),
    CONSTRAINT chk_audit_action CHECK (action_type IN ('INSERT', 'UPDATE', 'DELETE', 'STATUS_CHANGE')),
    CONSTRAINT chk_audit_old_object CHECK (old_values IS NULL OR jsonb_typeof(old_values) = 'object'),
    CONSTRAINT chk_audit_new_object CHECK (new_values IS NULL OR jsonb_typeof(new_values) = 'object')
);

-- SYSTEM_PARAMETERS (SEQ_SYSTEM_PARAM START WITH 1)
CREATE TABLE hrms.system_parameters (
    param_id             BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    param_group          VARCHAR(50)     NOT NULL,
    param_code           VARCHAR(50)     NOT NULL,
    param_value          VARCHAR(4000)   NOT NULL,
    param_description    VARCHAR(200),
    data_type            VARCHAR(20)     DEFAULT 'VARCHAR2',
    editable_flag        BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_system_params PRIMARY KEY (param_id),
    CONSTRAINT uk_param_code UNIQUE (param_group, param_code)
);

-- NOTIFICATION_QUEUE (SEQ_NOTIFICATION START WITH 1)
CREATE TABLE hrms.notification_queue (
    notification_id      BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    recipient_emp_id     BIGINT,
    recipient_email      VARCHAR(100),
    notification_type    VARCHAR(30)     NOT NULL,
    subject              VARCHAR(200)    NOT NULL,
    body                 TEXT            NOT NULL,
    status               VARCHAR(20)     DEFAULT 'PENDING',
    priority             INTEGER         DEFAULT 5,
    sent_date            TIMESTAMPTZ,
    error_message        VARCHAR(4000),
    retry_count          INTEGER         DEFAULT 0,
    reference_table      VARCHAR(60),
    reference_id         BIGINT,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_notif_queue PRIMARY KEY (notification_id),
    CONSTRAINT chk_notif_status CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'CANCELLED')),
    CONSTRAINT chk_notif_type CHECK (notification_type IN ('EMAIL', 'IN_APP', 'SMS'))
);

-- USER_SESSIONS (SEQ_USER_SESSION START WITH 1)
-- username widened to 100 (DEF-17, D-04). Token-hash and expiry columns for D-06 are
-- added by P2 together with user_credentials.
CREATE TABLE hrms.user_sessions (
    session_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    username             VARCHAR(100)    NOT NULL,
    login_time           TIMESTAMPTZ     NOT NULL,
    logout_time          TIMESTAMPTZ,
    ip_address           VARCHAR(50),
    forms_module         VARCHAR(100),
    session_status       VARCHAR(20)     DEFAULT 'ACTIVE',
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_user_sessions PRIMARY KEY (session_id),
    CONSTRAINT fk_us_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id)
);

-- LOOKUP_VALUES (SEQ_LOOKUP START WITH 1)
CREATE TABLE hrms.lookup_values (
    lookup_id            BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    lookup_type          VARCHAR(50)     NOT NULL,
    lookup_code          VARCHAR(50)     NOT NULL,
    lookup_value         VARCHAR(200)    NOT NULL,
    display_order        INTEGER         DEFAULT 0,
    parent_lookup_id     BIGINT,
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_lookup_values PRIMARY KEY (lookup_id),
    CONSTRAINT uk_lookup UNIQUE (lookup_type, lookup_code),
    CONSTRAINT fk_lookup_parent FOREIGN KEY (parent_lookup_id) REFERENCES hrms.lookup_values (lookup_id)
);
