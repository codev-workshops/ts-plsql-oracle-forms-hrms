-- Contract v1 uses a numeric locationId; locations stay keyed by location_code (PK and FKs unchanged).
-- Seeded rows are numbered in location_code order (CHI=1, HQ=2, SF=3); new rows get identity values from 100.
ALTER TABLE locations ADD COLUMN location_id BIGINT;

UPDATE locations l
SET location_id = n.rn
FROM (SELECT location_code, row_number() OVER (ORDER BY location_code COLLATE "C") AS rn FROM locations) n
WHERE n.location_code = l.location_code;

ALTER TABLE locations ALTER COLUMN location_id SET NOT NULL;
ALTER TABLE locations ALTER COLUMN location_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100);
ALTER TABLE locations ADD CONSTRAINT uq_locations_location_id UNIQUE (location_id);
