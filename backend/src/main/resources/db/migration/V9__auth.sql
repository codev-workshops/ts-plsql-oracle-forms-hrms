-- ============================================================================
-- P2: authentication, sessions and the permission matrix (checkpoint D-06)
--   user_credentials  : password hashes (BCrypt via DelegatingPasswordEncoder) + lockout (OQ-07)
--   user_sessions     : opaque bearer token stored as SHA-256 hex + absolute expiry (OQ-08)
--   permission_rules  : data-driven (module x action) matrix; seeded with legacy has_permission
-- ============================================================================

CREATE TABLE hrms.user_credentials (
    credential_id         BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id                BIGINT          NOT NULL,
    password_hash         VARCHAR(255)    NOT NULL,
    failed_attempts       INTEGER         DEFAULT 0 NOT NULL,
    locked_until          TIMESTAMPTZ,
    password_changed_date TIMESTAMPTZ,
    active_flag           BOOLEAN         DEFAULT true NOT NULL,
    created_by            VARCHAR(100)    NOT NULL,
    created_date          TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by           VARCHAR(100),
    modified_date         TIMESTAMPTZ,
    CONSTRAINT pk_user_credentials PRIMARY KEY (credential_id),
    CONSTRAINT uk_user_credentials_emp UNIQUE (emp_id),
    CONSTRAINT fk_uc_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT chk_uc_failed_attempts CHECK (failed_attempts >= 0)
);

COMMENT ON TABLE hrms.user_credentials IS 'Login credentials (D-06). The legacy USER_CREDENTIALS table was referenced but never existed';
COMMENT ON COLUMN hrms.user_credentials.password_hash IS 'DelegatingPasswordEncoder format, e.g. {bcrypt}$2a$...; MD5 is not supported';
COMMENT ON COLUMN hrms.user_credentials.failed_attempts IS 'Consecutive failed logins; reset on success (OQ-07)';

ALTER TABLE hrms.user_sessions
    ADD COLUMN token_hash VARCHAR(64),
    ADD COLUMN expires_at TIMESTAMPTZ,
    ADD CONSTRAINT uk_user_sessions_token UNIQUE (token_hash),
    ADD CONSTRAINT chk_session_status CHECK (session_status IS NULL OR session_status IN ('ACTIVE', 'CLOSED', 'EXPIRED'));

COMMENT ON COLUMN hrms.user_sessions.token_hash IS 'SHA-256 (hex) of the opaque bearer token; the token itself is never stored (D-06)';
COMMENT ON COLUMN hrms.user_sessions.expires_at IS 'login_time + 30 minutes, absolute (OQ-08)';

CREATE TABLE hrms.permission_rules (
    rule_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    module_code           VARCHAR(20),
    action_code           VARCHAR(20),
    min_grade_id          BIGINT          DEFAULT 0 NOT NULL,
    rule_description      VARCHAR(200)    NOT NULL,
    active_flag           BOOLEAN         DEFAULT true NOT NULL,
    created_by            VARCHAR(100)    NOT NULL,
    created_date          TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by           VARCHAR(100),
    modified_date         TIMESTAMPTZ,
    CONSTRAINT pk_permission_rules PRIMARY KEY (rule_id),
    CONSTRAINT chk_perm_module CHECK (module_code IS NULL OR module_code IN ('EMPLOYEE', 'PAYROLL', 'LEAVE', 'PERFORMANCE', 'REPORTS', 'ADMIN')),
    CONSTRAINT chk_perm_action CHECK (action_code IS NULL OR action_code IN ('VIEW', 'CREATE', 'EDIT', 'APPROVE', 'ADMIN')),
    CONSTRAINT chk_perm_min_grade CHECK (min_grade_id >= 0)
);

COMMENT ON TABLE hrms.permission_rules IS 'Permission matrix (D-06). A (module, action) is granted when any active rule matches it (NULL = any) and the employee job grade_id >= min_grade_id';

