-- DEF-05: tax parameters that PKG_PAYROLL hard-coded (pkb L7-14, L702-715) become data, seeded with the
-- 2024 values for parity. A run uses the latest tax_year <= the year of its period end, so the 2024 rows keep
-- applying to later years (exactly what the hard-coded constants did) until newer rows are added.
CREATE TABLE hrms.payroll_tax_parameters (
    param_id             BIGINT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tax_year             INTEGER         NOT NULL,
    param_code           VARCHAR(50)     NOT NULL,
    state_code           VARCHAR(3),
    param_value          NUMERIC(14,6)   NOT NULL,
    param_description    VARCHAR(200),
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_payroll_tax_parameters PRIMARY KEY (param_id),
    CONSTRAINT chk_ptp_code CHECK (param_code IN ('SS_WAGE_BASE', 'SS_RATE', 'MEDICARE_RATE', 'MEDICARE_ADDL_RATE',
        'MEDICARE_ADDL_THRESHOLD', 'STD_DEDUCTION_SINGLE', 'STD_DEDUCTION_MARRIED_JOINT', 'ALLOWANCE_AMOUNT',
        'STATE_RATE', 'STATE_DEFAULT_RATE')),
    CONSTRAINT chk_ptp_state CHECK ((param_code = 'STATE_RATE') = (state_code IS NOT NULL))
);
CREATE UNIQUE INDEX ux_payroll_tax_parameters ON hrms.payroll_tax_parameters (tax_year, param_code, COALESCE(state_code, ''));

