-- LEAVE_TYPES (SEQ_LEAVE_TYPE START WITH 1)
CREATE TABLE hrms.leave_types (
    leave_type_id        BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    leave_type_code      VARCHAR(20)     NOT NULL,
    leave_type_name      VARCHAR(50)     NOT NULL,
    paid_flag            BOOLEAN         DEFAULT true NOT NULL,
    accrual_flag         BOOLEAN         DEFAULT true NOT NULL,
    accrual_rate         NUMERIC(6,2),
    accrual_frequency    VARCHAR(20),
    max_balance          NUMERIC(6,2),
    carryover_max        NUMERIC(6,2),
    carryover_expiry     INTEGER,
    min_tenure_days      INTEGER         DEFAULT 0,
    requires_approval    BOOLEAN         DEFAULT true NOT NULL,
    requires_document    BOOLEAN         DEFAULT false NOT NULL,
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_leave_types PRIMARY KEY (leave_type_id),
    CONSTRAINT uk_leave_type_code UNIQUE (leave_type_code),
    CONSTRAINT chk_accrual_freq CHECK (accrual_frequency IS NULL OR accrual_frequency IN ('MONTHLY', 'BIWEEKLY', 'ANNUAL'))
);

COMMENT ON COLUMN hrms.leave_types.carryover_expiry IS 'Months after year end until carried-over days expire';

-- LEAVE_BALANCES (SEQ_LEAVE_BALANCE START WITH 1)
-- AVAILABLE: Oracle VIRTUAL column -> STORED generated column, identical formula (D-01).
CREATE TABLE hrms.leave_balances (
    balance_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    leave_type_id        BIGINT          NOT NULL,
    calendar_year        INTEGER         NOT NULL,
    opening_balance      NUMERIC(6,2)    DEFAULT 0,
    accrued              NUMERIC(6,2)    DEFAULT 0,
    used                 NUMERIC(6,2)    DEFAULT 0,
    adjustment           NUMERIC(6,2)    DEFAULT 0,
    pending              NUMERIC(6,2)    DEFAULT 0,
    available            NUMERIC(6,2)    GENERATED ALWAYS AS (opening_balance + accrued - used + adjustment - pending) STORED,
    carryover_from_prev  NUMERIC(6,2)    DEFAULT 0,
    carryover_expiry_dt  DATE,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_leave_balances PRIMARY KEY (balance_id),
    CONSTRAINT fk_lb_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT fk_lb_type FOREIGN KEY (leave_type_id) REFERENCES hrms.leave_types (leave_type_id),
    CONSTRAINT uk_leave_bal UNIQUE (emp_id, leave_type_id, calendar_year)
);

-- LEAVE_REQUESTS (SEQ_LEAVE_REQUEST START WITH 1)
CREATE TABLE hrms.leave_requests (
    request_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    leave_type_id        BIGINT          NOT NULL,
    start_date           DATE            NOT NULL,
    end_date             DATE            NOT NULL,
    total_days           NUMERIC(5,1)    NOT NULL,
    half_day_flag        BOOLEAN         DEFAULT false NOT NULL,
    half_day_period      VARCHAR(10),
    status               VARCHAR(20)     DEFAULT 'PENDING',
    reason               VARCHAR(4000),
    supporting_doc_path  VARCHAR(500),
    approver_emp_id      BIGINT,
    approval_date        TIMESTAMPTZ,
    approval_comments    VARCHAR(4000),
    cancel_reason        VARCHAR(4000),
    cancelled_date       TIMESTAMPTZ,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_leave_requests PRIMARY KEY (request_id),
    CONSTRAINT fk_lr_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT fk_lr_type FOREIGN KEY (leave_type_id) REFERENCES hrms.leave_types (leave_type_id),
    CONSTRAINT fk_lr_approver FOREIGN KEY (approver_emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT chk_lr_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'TAKEN')),
    CONSTRAINT chk_lr_dates CHECK (end_date >= start_date),
    CONSTRAINT chk_half_day CHECK (half_day_period IS NULL OR half_day_period IN ('AM', 'PM'))
);

-- LEAVE_ACCRUAL_LOG (SEQ_LEAVE_ACCRUAL START WITH 1)
CREATE TABLE hrms.leave_accrual_log (
    accrual_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    leave_type_id        BIGINT          NOT NULL,
    accrual_date         DATE            NOT NULL,
    accrual_amount       NUMERIC(6,2)    NOT NULL,
    balance_after        NUMERIC(6,2),
    run_id               BIGINT,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_leave_accrual_log PRIMARY KEY (accrual_id),
    CONSTRAINT fk_lal_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT fk_lal_type FOREIGN KEY (leave_type_id) REFERENCES hrms.leave_types (leave_type_id)
);

COMMENT ON COLUMN hrms.leave_accrual_log.run_id IS 'Accrual batch run identifier (not a payroll run; no FK in legacy)';

-- HOLIDAYS (SEQ_HOLIDAY START WITH 1)
CREATE TABLE hrms.holidays (
    holiday_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    holiday_date         DATE            NOT NULL,
    holiday_name         VARCHAR(100)    NOT NULL,
    location_code        VARCHAR(10),
    floating_flag        BOOLEAN         DEFAULT false NOT NULL,
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_holidays PRIMARY KEY (holiday_id),
    CONSTRAINT fk_hol_location FOREIGN KEY (location_code) REFERENCES hrms.locations (location_code)
);

COMMENT ON COLUMN hrms.holidays.location_code IS 'NULL = company-wide holiday; otherwise applies to that location only';
