-- P3 leave pilot (D-10: appended, never edits V1..V9).
-- Monthly accrual idempotency (PKG-L04, OQ-12): one run per calendar month replaces the
-- DBMS_SCHEDULER job, which could double-accrue when it was re-run.
CREATE TABLE hrms.leave_accrual_runs (
    run_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    accrual_period       DATE            NOT NULL,
    accrual_date         DATE            NOT NULL,
    employees_processed  INTEGER         NOT NULL,
    entries_created      INTEGER         NOT NULL,
    total_accrued        NUMERIC(9,2)    NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_leave_accrual_runs PRIMARY KEY (run_id),
    CONSTRAINT uk_accrual_period UNIQUE (accrual_period),
    CONSTRAINT chk_accrual_period CHECK (accrual_period = date_trunc('month', accrual_period)::date)
);

COMMENT ON TABLE hrms.leave_accrual_runs IS 'One row per monthly accrual run (P3, PKG-L04). accrual_period is the first day of the month';

ALTER TABLE hrms.leave_accrual_log
    ADD CONSTRAINT fk_lal_run FOREIGN KEY (run_id) REFERENCES hrms.leave_accrual_runs (run_id);

CREATE UNIQUE INDEX uk_lal_run_emp_type ON hrms.leave_accrual_log (run_id, emp_id, leave_type_id)
    WHERE run_id IS NOT NULL;

-- Approval inbox and dispatcher scans.
CREATE INDEX ix_leave_requests_emp_status ON hrms.leave_requests (emp_id, status, start_date);
