    leave_type_id     INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    leave_type_code   VARCHAR(20)  NOT NULL,
    leave_type_name   VARCHAR(50)  NOT NULL,
