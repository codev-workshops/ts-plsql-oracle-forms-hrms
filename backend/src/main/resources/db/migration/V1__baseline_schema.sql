    table_name       VARCHAR(60)  NOT NULL,
    record_id        BIGINT       NOT NULL,
    action_type      VARCHAR(10)  NOT NULL,
    old_values       TEXT,
    new_values       TEXT,
    changed_by       VARCHAR(100) NOT NULL,
    changed_date     TIMESTAMP    NOT NULL DEFAULT now(),
    ip_address       VARCHAR(50),
    session_id       VARCHAR(100),
    CONSTRAINT chk_audit_action CHECK (action_type IN ('INSERT', 'UPDATE', 'DELETE'))
);
CREATE INDEX ix_audit_table_record ON audit_log (table_name, record_id);
CREATE INDEX ix_audit_changed_date ON audit_log (changed_date);

