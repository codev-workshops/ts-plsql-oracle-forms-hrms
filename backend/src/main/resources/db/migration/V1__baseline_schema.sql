-- ============================================================================
-- V1 baseline schema: all 30 legacy HRMS tables + 6 views, ported from
-- schema/tables/*.sql and schema/views/hrms_views.sql (Oracle 19c -> Postgres).
-- Surrogate keys use identity columns whose start values sit above the seeded
-- IDs (fixes the legacy SEQ_* / seed collisions, inventory §2.6).
-- Owned by Phase 2 (platform). Phase 3 modules must NOT edit this file; add
-- follow-up migrations in their reserved range instead (slice-recipe.md).
-- ============================================================================

-- ---------------------------------------------------------------- core ------
CREATE TABLE departments (
    dept_id          BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    dept_code        VARCHAR(20)  NOT NULL,
    dept_name        VARCHAR(100) NOT NULL,
    parent_dept_id   BIGINT REFERENCES departments(dept_id),
    cost_center      VARCHAR(20),
    manager_emp_id   BIGINT,
    location_code    VARCHAR(10),
    active_flag      CHAR(1)      NOT NULL DEFAULT 'Y',
    created_by       VARCHAR(30)  NOT NULL,
    created_date     TIMESTAMP    NOT NULL DEFAULT now(),
    modified_by      VARCHAR(30),
    modified_date    TIMESTAMP,
    CONSTRAINT uk_dept_code UNIQUE (dept_code),
    CONSTRAINT chk_dept_active CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE locations (
    location_code    VARCHAR(10)  PRIMARY KEY,
    location_name    VARCHAR(100) NOT NULL,
    address_line1    VARCHAR(200),
    address_line2    VARCHAR(200),
    city             VARCHAR(100),
    state_province   VARCHAR(100),
    postal_code      VARCHAR(20),
    country_code     VARCHAR(3),
    phone_number     VARCHAR(30),
    timezone         VARCHAR(50)  DEFAULT 'America/New_York',
    active_flag      CHAR(1)      NOT NULL DEFAULT 'Y',
    created_by       VARCHAR(30)  NOT NULL,
    created_date     TIMESTAMP    NOT NULL DEFAULT now(),
    modified_by      VARCHAR(30),
    modified_date    TIMESTAMP
);

CREATE TABLE job_grades (
    grade_id          INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    grade_code        VARCHAR(10)   NOT NULL,
    grade_name        VARCHAR(50)   NOT NULL,
    min_salary        NUMERIC(12,2) NOT NULL,
    max_salary        NUMERIC(12,2) NOT NULL,
    overtime_eligible CHAR(1)       DEFAULT 'N',
    active_flag       CHAR(1)       NOT NULL DEFAULT 'Y',
    created_by        VARCHAR(30)   NOT NULL,
    created_date      TIMESTAMP     NOT NULL DEFAULT now(),
    modified_by       VARCHAR(30),
    modified_date     TIMESTAMP,
    CONSTRAINT uk_grade_code UNIQUE (grade_code),
    CONSTRAINT chk_salary_range CHECK (max_salary >= min_salary)
);

CREATE TABLE job_titles (
    job_id           BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    job_code         VARCHAR(20)  NOT NULL,
    job_title        VARCHAR(100) NOT NULL,
    job_family       VARCHAR(50),
    grade_id         INTEGER      NOT NULL REFERENCES job_grades(grade_id),
    eeo_category     VARCHAR(10),
    flsa_status      VARCHAR(10)  DEFAULT 'EXEMPT',
    active_flag      CHAR(1)      NOT NULL DEFAULT 'Y',
    created_by       VARCHAR(30)  NOT NULL,
    created_date     TIMESTAMP    NOT NULL DEFAULT now(),
    modified_by      VARCHAR(30),
    modified_date    TIMESTAMP,
    CONSTRAINT uk_job_code UNIQUE (job_code)
);

CREATE TABLE employees (
    emp_id             BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    emp_number         VARCHAR(20)  NOT NULL,
    first_name         VARCHAR(50)  NOT NULL,
    middle_name        VARCHAR(50),
    last_name          VARCHAR(50)  NOT NULL,
    date_of_birth      DATE,
    gender             CHAR(1),
    marital_status     VARCHAR(10),
    nationality        VARCHAR(50),
    ssn_encrypted      VARCHAR(200),
    email              VARCHAR(100),
    phone_work         VARCHAR(30),
    phone_mobile       VARCHAR(30),
    address_line1      VARCHAR(200),
    address_line2      VARCHAR(200),
    city               VARCHAR(100),
    state_province     VARCHAR(100),
    postal_code        VARCHAR(20),
    country_code       VARCHAR(3),
    hire_date          DATE         NOT NULL,
    termination_date   DATE,
    termination_reason VARCHAR(50),
    dept_id            BIGINT       NOT NULL REFERENCES departments(dept_id),
    job_id             BIGINT       NOT NULL REFERENCES job_titles(job_id),
    manager_emp_id     BIGINT       REFERENCES employees(emp_id),
    location_code      VARCHAR(10)  REFERENCES locations(location_code),
    employment_type    VARCHAR(20)  DEFAULT 'FULL_TIME',
    employment_status  VARCHAR(20)  DEFAULT 'ACTIVE',
    photo_blob         BYTEA,
    notes              TEXT,
    active_flag        CHAR(1)      NOT NULL DEFAULT 'Y',
    created_by         VARCHAR(30)  NOT NULL,
    created_date       TIMESTAMP    NOT NULL DEFAULT now(),
    modified_by        VARCHAR(30),
    modified_date      TIMESTAMP,
    CONSTRAINT uk_emp_number UNIQUE (emp_number),
    CONSTRAINT chk_emp_status CHECK (employment_status IN ('ACTIVE', 'ON_LEAVE', 'SUSPENDED', 'TERMINATED')),
    CONSTRAINT chk_emp_type CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERN')),
    CONSTRAINT chk_emp_gender CHECK (gender IN ('M', 'F', 'O'))
);
-- D3: email unique among active employees (case-insensitive)
CREATE UNIQUE INDEX uk_emp_email_active ON employees (lower(email)) WHERE active_flag = 'Y';
CREATE INDEX ix_emp_manager ON employees (manager_emp_id);
CREATE INDEX ix_emp_dept ON employees (dept_id);
-- Replaces legacy SEQ_EMP_NUMBER / MAX()+1 race (inventory §9)
CREATE SEQUENCE seq_emp_number START WITH 1000;

ALTER TABLE departments ADD CONSTRAINT fk_dept_manager FOREIGN KEY (manager_emp_id) REFERENCES employees(emp_id);
ALTER TABLE departments ADD CONSTRAINT fk_dept_location FOREIGN KEY (location_code) REFERENCES locations(location_code);

