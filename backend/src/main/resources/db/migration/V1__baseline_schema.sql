CREATE VIEW vw_active_employees AS
SELECT e.emp_id, e.emp_number, e.first_name, e.last_name,
       e.first_name || ' ' || e.last_name AS full_name,
       e.email, e.phone_work, e.phone_mobile, e.hire_date,
       trunc((EXTRACT(YEAR FROM age(current_date, e.hire_date)) * 12
              + EXTRACT(MONTH FROM age(current_date, e.hire_date))) / 12.0, 1) AS tenure_years,
       e.employment_type, e.employment_status,
       e.dept_id, d.dept_name, d.dept_code, d.cost_center,
       e.job_id, j.job_title, j.job_code,
       g.grade_id, g.grade_name,
       e.manager_emp_id,
       m.first_name || ' ' || m.last_name AS manager_name,
       e.location_code, l.location_name, l.city, l.state_province, l.country_code,
       sr.base_salary AS current_salary, sr.currency_code, sr.pay_frequency
FROM employees e
JOIN departments d ON e.dept_id = d.dept_id
JOIN job_titles j ON e.job_id = j.job_id
JOIN job_grades g ON j.grade_id = g.grade_id
LEFT JOIN employees m ON e.manager_emp_id = m.emp_id
LEFT JOIN locations l ON e.location_code = l.location_code
LEFT JOIN salary_records sr ON e.emp_id = sr.emp_id
     AND sr.active_flag = 'Y'
     AND sr.effective_date <= current_date
     AND (sr.end_date IS NULL OR sr.end_date > current_date)
WHERE e.employment_status = 'ACTIVE'
  AND e.active_flag = 'Y';

CREATE VIEW vw_org_hierarchy AS
WITH RECURSIVE org AS (
    SELECT emp_id, emp_number, first_name || ' ' || last_name AS emp_name,
           manager_emp_id, dept_id, 1 AS org_level,
           ' > ' || first_name || ' ' || last_name AS org_path,
           ARRAY[last_name::text, emp_id::text] AS sort_path
    FROM employees
    WHERE employment_status = 'ACTIVE' AND manager_emp_id IS NULL
    UNION ALL
    SELECT e.emp_id, e.emp_number, e.first_name || ' ' || e.last_name,
           e.manager_emp_id, e.dept_id, o.org_level + 1,
           o.org_path || ' > ' || e.first_name || ' ' || e.last_name,
           o.sort_path || ARRAY[e.last_name::text, e.emp_id::text]
    FROM employees e
    JOIN org o ON e.manager_emp_id = o.emp_id
    WHERE e.employment_status = 'ACTIVE' AND o.org_level < 50
)
SELECT o.emp_id, o.emp_number, o.emp_name, o.manager_emp_id, o.dept_id, o.org_level, o.org_path,
       CASE WHEN EXISTS (SELECT 1 FROM employees c
                         WHERE c.manager_emp_id = o.emp_id AND c.employment_status = 'ACTIVE')
            THEN 0 ELSE 1 END AS is_leaf,
       o.sort_path
FROM org o;

CREATE VIEW vw_employee_compensation AS
SELECT e.emp_id, e.emp_number,
       e.first_name || ' ' || e.last_name AS emp_name,
       d.dept_name, j.job_title, g.grade_name,
       sr.base_salary,
       g.min_salary AS grade_min,
       g.max_salary AS grade_max,
       (g.min_salary + g.max_salary) / 2 AS grade_midpoint,
       round(sr.base_salary / ((g.min_salary + g.max_salary) / 2) * 100, 1) AS compa_ratio,
       sr.effective_date AS salary_effective_date,
       sr.change_reason AS last_change_reason,
       sr.change_pct AS last_change_pct
FROM employees e
JOIN departments d ON e.dept_id = d.dept_id
JOIN job_titles j ON e.job_id = j.job_id
JOIN job_grades g ON j.grade_id = g.grade_id
JOIN salary_records sr ON e.emp_id = sr.emp_id AND sr.active_flag = 'Y'
WHERE e.employment_status = 'ACTIVE';

-- available excludes pending (as legacy view); API exposes pending separately (D14)
CREATE VIEW vw_leave_summary AS
SELECT e.emp_id, e.emp_number,
       e.first_name || ' ' || e.last_name AS emp_name,
       d.dept_name, lt.leave_type_name,
       lb.opening_balance, lb.accrued, lb.used, lb.adjustment, lb.pending,
       lb.opening_balance + lb.accrued - lb.used + lb.adjustment AS available,
       round(lb.used * 100 / NULLIF(lb.opening_balance + lb.accrued, 0), 1) AS utilization_pct
FROM leave_balances lb
JOIN employees e ON lb.emp_id = e.emp_id
JOIN departments d ON e.dept_id = d.dept_id
JOIN leave_types lt ON lb.leave_type_id = lt.leave_type_id
WHERE lb.calendar_year = EXTRACT(YEAR FROM current_date)
  AND e.employment_status = 'ACTIVE';

-- deductions = DEDUCTION + TAX + BENEFIT (single definition, inventory §9)
CREATE VIEW vw_payroll_latest AS
SELECT pd.emp_id, e.emp_number,
       e.first_name || ' ' || e.last_name AS emp_name,
       pp.period_name,
       SUM(CASE WHEN pd.element_type = 'EARNING' THEN pd.amount ELSE 0 END) AS gross_pay,
       SUM(CASE WHEN pd.element_type = 'TAX' THEN abs(pd.amount) ELSE 0 END) AS total_taxes,
       SUM(CASE WHEN pd.element_type IN ('DEDUCTION', 'BENEFIT') THEN abs(pd.amount) ELSE 0 END) AS total_deductions,
       SUM(pd.amount) AS net_pay
FROM payroll_details pd
JOIN employees e ON pd.emp_id = e.emp_id
JOIN payroll_runs pr ON pd.run_id = pr.run_id
JOIN pay_periods pp ON pr.period_id = pp.period_id
WHERE pr.run_id = (SELECT max(pr2.run_id) FROM payroll_runs pr2 WHERE pr2.status = 'APPROVED')
  AND pd.status <> 'ERROR'
GROUP BY pd.emp_id, e.emp_number, e.first_name || ' ' || e.last_name, pp.period_name;

CREATE VIEW vw_pending_approvals AS
SELECT 'LEAVE' AS approval_type,
       lr.request_id AS item_id,
       lr.approver_emp_id AS approver_id,
       e.first_name || ' ' || e.last_name AS requestor_name,
       lt.leave_type_name AS item_description,
       lr.created_date AS request_date,
       lr.total_days || ' day(s) ' || to_char(lr.start_date, 'MM/DD') || '-' || to_char(lr.end_date, 'MM/DD') AS details
FROM leave_requests lr
JOIN employees e ON lr.emp_id = e.emp_id
JOIN leave_types lt ON lr.leave_type_id = lt.leave_type_id
WHERE lr.status = 'PENDING'
UNION ALL
SELECT 'PERFORMANCE',
       pr.review_id,
       pr.reviewer_emp_id,
       e.first_name || ' ' || e.last_name,
       'Performance Review - ' || rc.cycle_name,
       pr.created_date,
       pr.status
FROM performance_reviews pr
JOIN employees e ON pr.emp_id = e.emp_id
JOIN review_cycles rc ON pr.cycle_id = rc.cycle_id
WHERE pr.status = 'MANAGER_REVIEW';
