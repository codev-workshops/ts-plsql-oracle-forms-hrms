CREATE TABLE leave_balances (
    balance_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id              BIGINT       NOT NULL REFERENCES employees(emp_id),
    leave_type_id       INTEGER      NOT NULL REFERENCES leave_types(leave_type_id),
    calendar_year       SMALLINT     NOT NULL,
    opening_balance     NUMERIC(6,2) NOT NULL DEFAULT 0,
    accrued             NUMERIC(6,2) NOT NULL DEFAULT 0,
    used                NUMERIC(6,2) NOT NULL DEFAULT 0,
    adjustment          NUMERIC(6,2) NOT NULL DEFAULT 0,
    pending             NUMERIC(6,2) NOT NULL DEFAULT 0,
    available           NUMERIC(6,2) GENERATED ALWAYS AS (opening_balance + accrued - used + adjustment - pending) STORED,
    carryover_from_prev NUMERIC(6,2) NOT NULL DEFAULT 0,
    carryover_expiry_dt DATE,
    created_by          VARCHAR(30)  NOT NULL,
    created_date        TIMESTAMP    NOT NULL DEFAULT now(),
    modified_by         VARCHAR(30),
    modified_date       TIMESTAMP,
    CONSTRAINT uk_leave_bal UNIQUE (emp_id, leave_type_id, calendar_year)
);

