-- DEPARTMENTS (SEQ_DEPARTMENT START WITH 100)
CREATE TABLE hrms.departments (
    dept_id              BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    dept_code            VARCHAR(20)     NOT NULL,
    dept_name            VARCHAR(100)    NOT NULL,
    parent_dept_id       BIGINT,
    cost_center          VARCHAR(20),
    manager_emp_id       BIGINT,
    location_code        VARCHAR(10),
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_departments PRIMARY KEY (dept_id),
    CONSTRAINT uk_dept_code UNIQUE (dept_code)
);

COMMENT ON TABLE hrms.departments IS 'Organization departments and cost centers';
COMMENT ON COLUMN hrms.departments.parent_dept_id IS 'Self-referencing FK for department hierarchy';
COMMENT ON COLUMN hrms.departments.cost_center IS 'Financial cost center code for GL integration';

-- LOCATIONS (natural key; SEQ_LOCATION was never used for a column)
CREATE TABLE hrms.locations (
    location_code        VARCHAR(10)     NOT NULL,
    location_name        VARCHAR(100)    NOT NULL,
    address_line1        VARCHAR(200),
    address_line2        VARCHAR(200),
    city                 VARCHAR(100),
    state_province       VARCHAR(100),
    postal_code          VARCHAR(20),
    country_code         VARCHAR(3),
    phone_number         VARCHAR(30),
    timezone             VARCHAR(50)     DEFAULT 'America/New_York',
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_locations PRIMARY KEY (location_code)
);

-- JOB_GRADES (SEQ_JOB_GRADE START WITH 100)
CREATE TABLE hrms.job_grades (
    grade_id             BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    grade_code           VARCHAR(10)     NOT NULL,
    grade_name           VARCHAR(50)     NOT NULL,
    min_salary           NUMERIC(12,2)   NOT NULL,
    max_salary           NUMERIC(12,2)   NOT NULL,
    overtime_eligible    BOOLEAN         DEFAULT false NOT NULL,
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_job_grades PRIMARY KEY (grade_id),
    CONSTRAINT uk_grade_code UNIQUE (grade_code),
    CONSTRAINT chk_salary_range CHECK (max_salary >= min_salary)
);

-- JOB_TITLES (SEQ_JOB_TITLE START WITH 100)
CREATE TABLE hrms.job_titles (
    job_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 100) NOT NULL,
    job_code             VARCHAR(20)     NOT NULL,
    job_title            VARCHAR(100)    NOT NULL,
    job_family           VARCHAR(50),
    grade_id             BIGINT          NOT NULL,
    eeo_category         VARCHAR(10),
    flsa_status          VARCHAR(10)     DEFAULT 'EXEMPT',
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_job_titles PRIMARY KEY (job_id),
    CONSTRAINT uk_job_code UNIQUE (job_code),
    CONSTRAINT fk_job_grade FOREIGN KEY (grade_id) REFERENCES hrms.job_grades (grade_id)
);

-- EMPLOYEES (SEQ_EMPLOYEE START WITH 10000)
CREATE TABLE hrms.employees (
    emp_id               BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) NOT NULL,
    emp_number           VARCHAR(20)     NOT NULL,
    first_name           VARCHAR(50)     NOT NULL,
    middle_name          VARCHAR(50),
    last_name            VARCHAR(50)     NOT NULL,
    date_of_birth        DATE,
    gender               VARCHAR(1),
    marital_status       VARCHAR(10),
    nationality          VARCHAR(50),
    ssn_encrypted        VARCHAR(200),
    email                VARCHAR(100),
    phone_work           VARCHAR(30),
    phone_mobile         VARCHAR(30),
    address_line1        VARCHAR(200),
    address_line2        VARCHAR(200),
    city                 VARCHAR(100),
    state_province       VARCHAR(100),
    postal_code          VARCHAR(20),
    country_code         VARCHAR(3),
    hire_date            DATE            NOT NULL,
    termination_date     DATE,
    termination_reason   VARCHAR(50),
    dept_id              BIGINT          NOT NULL,
    job_id               BIGINT          NOT NULL,
    manager_emp_id       BIGINT,
    location_code        VARCHAR(10),
    employment_type      VARCHAR(20)     DEFAULT 'FULL_TIME',
    employment_status    VARCHAR(20)     DEFAULT 'ACTIVE',
    photo_blob           BYTEA,
    notes                TEXT,
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_employees PRIMARY KEY (emp_id),
    CONSTRAINT uk_emp_number UNIQUE (emp_number),
    CONSTRAINT fk_emp_dept FOREIGN KEY (dept_id) REFERENCES hrms.departments (dept_id),
    CONSTRAINT fk_emp_job FOREIGN KEY (job_id) REFERENCES hrms.job_titles (job_id),
    CONSTRAINT fk_emp_manager FOREIGN KEY (manager_emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT fk_emp_location FOREIGN KEY (location_code) REFERENCES hrms.locations (location_code),
    CONSTRAINT chk_emp_status CHECK (employment_status IN ('ACTIVE', 'ON_LEAVE', 'SUSPENDED', 'TERMINATED')),
    CONSTRAINT chk_emp_type CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERN')),
    CONSTRAINT chk_emp_gender CHECK (gender IS NULL OR gender IN ('M', 'F', 'O'))
);

COMMENT ON TABLE hrms.employees IS 'Master employee records - core entity of the HRMS system';
COMMENT ON COLUMN hrms.employees.ssn_encrypted IS 'Encrypted SSN; the key comes from external configuration, never from source (D-06)';
COMMENT ON COLUMN hrms.employees.employment_status IS 'Current status: ACTIVE, ON_LEAVE, SUSPENDED, TERMINATED';
COMMENT ON COLUMN hrms.employees.emp_number IS 'EMP-NNNNNN, generated from hrms.seq_emp_number (D-02)';

-- Department integrity FKs that the Oracle DDL documents but never declared (P1 addition).
ALTER TABLE hrms.departments
    ADD CONSTRAINT fk_dept_parent FOREIGN KEY (parent_dept_id) REFERENCES hrms.departments (dept_id),
    ADD CONSTRAINT fk_dept_manager FOREIGN KEY (manager_emp_id) REFERENCES hrms.employees (emp_id),
    ADD CONSTRAINT fk_dept_location FOREIGN KEY (location_code) REFERENCES hrms.locations (location_code);

-- EMPLOYEE_HISTORY (SEQ_EMP_HISTORY START WITH 1)
CREATE TABLE hrms.employee_history (
    hist_id              BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    change_type          VARCHAR(30)     NOT NULL,
    effective_date       DATE            NOT NULL,
    old_dept_id          BIGINT,
    new_dept_id          BIGINT,
    old_job_id           BIGINT,
    new_job_id           BIGINT,
    old_manager_id       BIGINT,
    new_manager_id       BIGINT,
    old_salary           NUMERIC(12,2),
    new_salary           NUMERIC(12,2),
    old_location         VARCHAR(10),
    new_location         VARCHAR(10),
    reason_code          VARCHAR(30),
    comments             VARCHAR(4000),
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_emp_history PRIMARY KEY (hist_id),
    CONSTRAINT fk_hist_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT chk_change_type CHECK (change_type IN (
        'HIRE', 'TRANSFER', 'PROMOTION', 'DEMOTION', 'SALARY_CHANGE',
        'TERMINATION', 'REHIRE', 'LEAVE_START', 'LEAVE_END', 'STATUS_CHANGE'
    ))
);

-- EMPLOYEE_DEPENDENTS (SEQ_DEPENDENT START WITH 1)
CREATE TABLE hrms.employee_dependents (
    dependent_id         BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    first_name           VARCHAR(50)     NOT NULL,
    last_name            VARCHAR(50)     NOT NULL,
    relationship         VARCHAR(20)     NOT NULL,
    date_of_birth        DATE,
    ssn_encrypted        VARCHAR(200),
    benefits_enrolled    BOOLEAN         DEFAULT false NOT NULL,
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_emp_dependents PRIMARY KEY (dependent_id),
    CONSTRAINT fk_dep_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id),
    CONSTRAINT chk_relationship CHECK (relationship IN ('SPOUSE', 'CHILD', 'PARENT', 'DOMESTIC_PARTNER', 'OTHER'))
);

-- EMERGENCY_CONTACTS (SEQ_EMERGENCY_CONTACT START WITH 1)
CREATE TABLE hrms.emergency_contacts (
    contact_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    emp_id               BIGINT          NOT NULL,
    contact_name         VARCHAR(100)    NOT NULL,
    relationship         VARCHAR(30),
    phone_primary        VARCHAR(30)     NOT NULL,
    phone_secondary      VARCHAR(30),
    email                VARCHAR(100),
    priority_order       INTEGER         DEFAULT 1,
    active_flag          BOOLEAN         DEFAULT true NOT NULL,
    created_by           VARCHAR(100)    NOT NULL,
    created_date         TIMESTAMPTZ     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    modified_by          VARCHAR(100),
    modified_date        TIMESTAMPTZ,
    CONSTRAINT pk_emergency_contacts PRIMARY KEY (contact_id),
    CONSTRAINT fk_ec_emp FOREIGN KEY (emp_id) REFERENCES hrms.employees (emp_id)
);

-- EMP_NUMBER generator (D-02). Replaces PKG_EMPLOYEE.generate_emp_number MAX()+1.
CREATE SEQUENCE hrms.seq_emp_number START WITH 1000 INCREMENT BY 1;
