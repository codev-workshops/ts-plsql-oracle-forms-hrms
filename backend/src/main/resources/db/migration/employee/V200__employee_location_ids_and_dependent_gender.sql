-- Contract v1 identifies locations by a numeric locationId; LOCATIONS (owned by Employee) is keyed by code.
ALTER TABLE locations ADD COLUMN location_id BIGINT;
UPDATE locations l
SET location_id = s.rn
FROM (SELECT location_code, row_number() OVER (ORDER BY location_code) AS rn FROM locations) s
WHERE s.location_code = l.location_code;
ALTER TABLE locations ALTER COLUMN location_id SET NOT NULL;
ALTER TABLE locations ALTER COLUMN location_id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100);
ALTER TABLE locations ADD CONSTRAINT uk_location_id UNIQUE (location_id);

