package com.hrms.payroll;

import com.hrms.common.ApiException;
import com.hrms.common.AuditWriter;
import com.hrms.common.ErrorCode;
import com.hrms.payroll.PayrollModels.PayFrequency;
import com.hrms.payroll.PayrollModels.PayPeriod;
import com.hrms.payroll.PayrollModels.PayPeriodGeneration;
import com.hrms.payroll.PayrollModels.PayPeriodStatus;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.Clock;
import java.time.DayOfWeek;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.time.format.TextStyle;
import java.time.temporal.ChronoUnit;
import java.time.temporal.TemporalAdjusters;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/** Pay periods: PKG_PAYROLL.create_pay_periods (PKG-P02), close_pay_period (PKG-P04), the HRMS_PAYROLL list. */
@Service
public class PayPeriodService {

    static final String TABLE = "PAY_PERIODS";
    private static final String SELECT = """
            SELECT period_id, period_name, pay_frequency, period_start_date, period_end_date, pay_date, status,
                   closed_by, closed_date
            FROM hrms.pay_periods
            """;

    private final JdbcClient jdbc;
    private final AuditWriter audit;
    private final Clock clock;

    public PayPeriodService(JdbcClient jdbc, AuditWriter audit, Clock clock) {
        this.jdbc = jdbc;
        this.audit = audit;
        this.clock = clock;
    }

    /** A period as generated by create_pay_periods, before it is stored. */
    record PeriodSpec(String name, LocalDate start, LocalDate end, LocalDate payDate) {
    }

    /** FRM-061: the form's DEFAULT_WHERE {@code STATUS = 'OPEN' ORDER BY PERIOD_START_DATE DESC} is the default. */
    @Transactional(readOnly = true)
    public List<PayPeriod> list(PayPeriodStatus status, PayFrequency frequency, Integer year) {
        return jdbc.sql(SELECT + """
                WHERE status = :status
                  AND (CAST(:freq AS varchar) IS NULL OR pay_frequency = :freq)
                  AND (CAST(:year AS integer) IS NULL OR EXTRACT(YEAR FROM pay_date) = :year)
                ORDER BY period_start_date DESC, period_id DESC
                """).param("status", (status == null ? PayPeriodStatus.OPEN : status).name())
                .param("freq", frequency == null ? null : frequency.name()).param("year", year)
                .query(PayPeriodService::period).list();
    }

    @Transactional(readOnly = true)
    public PayPeriod get(long periodId) {
        return jdbc.sql(SELECT + " WHERE period_id = :id").param("id", periodId).query(PayPeriodService::period)
                .optional().orElseThrow(() -> notFound(periodId));
    }

    /**
     * create_pay_periods for MONTHLY or BIWEEKLY (legacy generated nothing for other frequencies; here that is
     * 400). Idempotent (DEF-P6-3 fix): a period that overlaps an existing period of the same frequency is skipped,
     * so a re-run or the next year's generation never duplicates a period. One transaction (legacy committed).
     */
    @Transactional
    public PayPeriodGeneration generate(int year, PayFrequency frequency, PayrollCaller caller) {
        List<PeriodSpec> specs = switch (frequency) {
            case MONTHLY -> monthly(year);
            case BIWEEKLY -> biweekly(year);
            default -> throw new ApiException(ErrorCode.VALIDATION_FAILED,
                    "Pay periods can be generated for MONTHLY or BIWEEKLY only");
        };
        jdbc.sql("SELECT pg_advisory_xact_lock(6, :f)").param("f", frequency.ordinal()).query((rs, i) -> 1).list();
        OffsetDateTime now = OffsetDateTime.now(clock).truncatedTo(ChronoUnit.MICROS);
        List<PayPeriod> created = new ArrayList<>();
        for (PeriodSpec s : specs) {
            jdbc.sql("""
                    INSERT INTO hrms.pay_periods (period_name, pay_frequency, period_start_date, period_end_date,
                        pay_date, status, created_by, created_date)
                    SELECT :name, :freq, :start, :end, :pay, 'OPEN', :actor, :now
                    WHERE NOT EXISTS (SELECT 1 FROM hrms.pay_periods WHERE pay_frequency = :freq
                                      AND period_start_date <= :end AND period_end_date >= :start)
                    RETURNING period_id
                    """).param("name", s.name()).param("freq", frequency.name()).param("start", s.start())
                    .param("end", s.end()).param("pay", s.payDate()).param("actor", caller.actor())
                    .param("now", now).query(Long.class).optional().ifPresent(id -> created.add(get(id)));
        }
        return new PayPeriodGeneration(year, frequency, created, specs.size() - created.size());
    }

    /** MONTHLY: calendar months, pay on the last day, moved back to Friday from a weekend. */
    static List<PeriodSpec> monthly(int year) {
        List<PeriodSpec> out = new ArrayList<>();
        for (int m = 1; m <= 12; m++) {
            LocalDate start = LocalDate.of(year, m, 1);
            LocalDate end = start.with(TemporalAdjusters.lastDayOfMonth());
            LocalDate pay = switch (end.getDayOfWeek()) {
                case SATURDAY -> end.minusDays(1);
                case SUNDAY -> end.minusDays(2);
                default -> end;
            };
            out.add(new PeriodSpec("%d-%02d (%s)".formatted(year, m,
                    start.getMonth().getDisplayName(TextStyle.SHORT, Locale.ENGLISH)), start, end, pay));
        }
        return out;
    }

    /**
     * BIWEEKLY: the first period ends on the year's first Friday (start = that Friday - 13); 14-day periods while
     * the start is in the year; pay = end + 5; name {@code YYYY-BW-NN}.
     */
    static List<PeriodSpec> biweekly(int year) {
        List<PeriodSpec> out = new ArrayList<>();
        LocalDate start = LocalDate.of(year, 1, 1).with(TemporalAdjusters.nextOrSame(DayOfWeek.FRIDAY)).minusDays(13);
        int n = 0;
        while (start.getYear() <= year) {
            LocalDate end = start.plusDays(13);
            n++;
            if (start.getYear() == year || end.getYear() == year) {
                out.add(new PeriodSpec("%d-BW-%02d".formatted(year, n), start, end, end.plusDays(5)));
            }
            start = end.plusDays(1);
        }
        return out;
    }

    /** close_pay_period: CLOSED is final (-20102). */
    @Transactional
    public PayPeriod close(long periodId, PayrollCaller caller) {
        String status = jdbc.sql("SELECT status FROM hrms.pay_periods WHERE period_id = :id FOR UPDATE")
                .param("id", periodId).query(String.class).optional().orElseThrow(() -> notFound(periodId));
        if (PayPeriodStatus.CLOSED.name().equals(status)) {
            throw new ApiException(ErrorCode.PERIOD_CLOSED, "Period already closed: " + periodId);
        }
        OffsetDateTime now = OffsetDateTime.now(clock).truncatedTo(ChronoUnit.MICROS);
        jdbc.sql("""
                UPDATE hrms.pay_periods SET status = 'CLOSED', closed_by = :actor, closed_date = :now,
                    modified_by = :actor, modified_date = :now
                WHERE period_id = :id
                """).param("actor", caller.actor()).param("now", now).param("id", periodId).update();
        audit.write(TABLE, periodId, "STATUS_CHANGE", Map.of("status", status), Map.of("status", "CLOSED"),
                caller.actor(), caller.ipAddress(), caller.sessionId());
        return get(periodId);
    }

    static ApiException notFound(long periodId) {
        return new ApiException(ErrorCode.NOT_FOUND, "Pay period not found: " + periodId);
    }

    private static PayPeriod period(ResultSet rs, int i) throws SQLException {
        return new PayPeriod(rs.getLong(1), rs.getString(2), PayFrequency.valueOf(rs.getString(3)),
                rs.getObject(4, LocalDate.class), rs.getObject(5, LocalDate.class), rs.getObject(6, LocalDate.class),
                PayPeriodStatus.valueOf(rs.getString(7)), rs.getString(8), rs.getObject(9, OffsetDateTime.class));
    }
}
